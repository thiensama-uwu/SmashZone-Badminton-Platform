const { BOOKING_STATES, SLOT_STATES } = require("../../../shared/constants/booking");

const transitions = {
  [BOOKING_STATES.PENDING_HOLD]: [BOOKING_STATES.PENDING_PAYMENT, BOOKING_STATES.EXPIRED],
  [BOOKING_STATES.PENDING_PAYMENT]: [BOOKING_STATES.CONFIRMED, BOOKING_STATES.CANCELLED],
  [BOOKING_STATES.CONFIRMED]: [BOOKING_STATES.CHECKED_IN, BOOKING_STATES.CANCELLED, BOOKING_STATES.REFUND_PENDING, BOOKING_STATES.PENDING_PAYMENT],
  [BOOKING_STATES.CHECKED_IN]: [BOOKING_STATES.COMPLETED],
  [BOOKING_STATES.REFUND_PENDING]: [BOOKING_STATES.REFUNDED],
};

function canTransition(from, to) {
  return Array.isArray(transitions[from]) && transitions[from].includes(to);
}

module.exports = {
  canTransition,
  transitions,
  BOOKING_STATES,
  SLOT_STATES,
};
